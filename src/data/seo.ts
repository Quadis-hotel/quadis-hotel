export type StaticSeoPath = keyof typeof STATIC_PAGE_SEO

/**
 * Meta for a static route, ready to spread onto <Seo>.
 *
 * The route path doubles as the canonical path, so /hotels?city=Noida and
 * /hotels?city=New%20Delhi cannot present as two indexable URLs with identical
 * copy. Entries that pin their own canonicalPath (the legal pages) win.
 */
export function pageSeo(path: StaticSeoPath): SeoMeta {
  const meta: PageMeta = STATIC_PAGE_SEO[path]
  return {
    title: meta.title,
    description: meta.description,
    image: meta.image,
    ogType: meta.ogType,
    noIndex: meta.noIndex,
    canonicalPath: meta.canonicalPath ?? (path === '/404' ? undefined : path),
  }
}

