/** Props <Seo> accepts. Kept here so page components import from one module. */
export interface SeoMeta {
  title: string
  description: string
  image?: string
  ogType?: string
  noIndex?: boolean
  canonicalPath?: string
}

export interface PageMeta extends SeoMeta {
  /**
   * Crawl priority for this route in sitemap.xml, or null to keep it out of
   * the sitemap entirely (auth and account pages, which also carry noIndex).
   *
   * It lives HERE rather than in the sitemap script on purpose: the two lists
   * were maintained separately, so a route could be given meta and quietly
   * never be submitted, or be submitted with no meta. generate-sitemap.mjs now
   * reads this file, and the two cannot drift.
   */
  sitemapPriority: string | null
}

