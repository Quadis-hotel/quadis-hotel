/**
 * Several property names already contain their own area or city — "Hotel
 * Downtown Sector 15 Noida" carries both — while others carry neither ("Hotel
 * Amar Inn"). Appending unconditionally produced "Hotel Downtown Sector 15
 * Noida, Sector 15, Noida", which reads like a broken template and wastes the
 * ~60 characters Google actually shows. So each part is added only if the name
 * is not already saying it.
 */
const appendIfMissing = (base: string, part: string): string =>
  base.toLowerCase().includes(part.toLowerCase()) ? base : `${base}, ${part}`

/**
 * Meta for one hotel landing page, derived entirely from src/data/hotels.ts.
 *
 * The title leads with the property and its locality because that is how guests
 * search ("hotel in sector 51 noida", "budget hotel lajpat nagar"), and the
 * description carries the three facts that decide a click on a budget booking:
 * where it is relative to the metro, the nightly rate, and the guest rating.
 *
 * `image` is passed in rather than derived: the page already resolves its
 * photography through the Vite asset glob, which hashes filenames, so there is
 * no stable public path this module could guess.
 */
export function hotelSeo(hotel: Hotel, image?: string): SeoMeta {
  const place = appendIfMissing(hotel.name, hotel.area)

  // If the name or area already said "Noida", saying it a third time in the
  // same title is spam, not signal — and it costs characters the title cannot
  // spare. Every generated title stays inside ~63 characters before the brand
  // suffix, which is roughly where Google's results page starts truncating.
  const qualifier = place.toLowerCase().includes(hotel.city.toLowerCase())
    ? 'Budget Rooms & Tariff'
    : `Budget Hotel in ${hotel.city}`

  const metro = hotel.transit?.metro
  const near = metro ? ` — ${metro.value} from ${metro.name}` : ''

  return {
    title: `${place} — ${qualifier}`,
    description: `Budget rooms at ${hotel.name} in ${hotel.area}, ${hotel.city}${near}. From ${inr(hotel.price)} a night, rated ${hotel.rating.toFixed(1)}/5. Book direct.`,
    image,
    canonicalPath: `/hotels/${hotel.slug}`,
  }
}

/**
 * Meta for one banquet landing page, derived entirely from BANQUETS.
 *
 * Leads with "Banquet Hall in <area>, <city>" because the search that matters
 * here is the locality one, not the brand one — nobody types "Banquets at Hotel
 * Amby Inn" into Google. The property name follows so the two Delhi venues stay
 * distinguishable in a results page.
 *
 * Capacities are the client's own figures (feedback, 5 Aug 2026), so a snippet
 * promising 65 guests is a number she stands behind.
 */
export function banquetSeo(venue: BanquetVenue, image?: string): SeoMeta {
  const property = venue.name.replace(/^Banquets at\s+/i, '')

  return {
    title: `Banquet Hall in ${venue.area}, ${venue.city} — ${property}`,
    description: `${property}’s banquet hall in ${venue.area}, ${venue.city} seats up to ${venue.capacity} guests across ${venue.hallArea}, with ${venue.catering.toLowerCase()} catering and ${venue.parking.toLowerCase()}.`,
    image,
    canonicalPath: `/banquets/${venue.slug}`,
  }
}
